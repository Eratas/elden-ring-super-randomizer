// test_shops_periodic.cpp - host-side tests for the manifest parser and roll, on a real manifest.
//
// Build: g++ -std=c++17 -O2 -Wall -Wextra test_shops_periodic.cpp manifest.cpp -o test_shops_periodic
//   or: use the small local build_test in build.ps1.
#include "manifest.h"

#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <random>
#include <string>

using namespace shops_periodic;

static int g_failures = 0;

static void check(bool ok, const char* what) {
    if (!ok) {
        std::printf("FAIL: %s\n", what);
        ++g_failures;
    }
}

// A tiny fixture keeps build.ps1 self-contained; a real manifest can be passed to validate it too.
static const char* kFixture() {
    static const std::string fixture =
        "# generated by the Super Randomizer\n"
        "bind 2111760 fe3e25833098e16b\n"
        "every 15\n"
        "pool 1 111 150 190\n"
        "pool 2 1000000 1010000\n"
        "shop 0 1000 1 1001 2\n";
    const char* path = "shops_periodic_fixture.txt";
    std::ofstream f(path);
    f << fixture;
    return path;
}

int main(int argc, char** argv) {
    const char* path = argc >= 2 ? argv[1] : kFixture();
    Manifest m;
    std::string err;
    if (!load_manifest(path, m, err)) {
        std::printf("FAIL: load_manifest(%s): %s\n", path, err.c_str());
        return 1;
    }
    check(m.every_minutes == 15 || m.every_minutes > 0, "every not parsed (>0)");
    check(m.bind != 0, "bind not parsed");
    check(m.valid(), "manifest invalid after load");
    check(!m.pools.empty(), "no pools parsed");
    check(m.shop_count() > 0, "no shop blocks parsed");
    for (const auto& pool : m.pools) {
        check(!pool.second.empty(), "pool with zero entries");
    }
    // roll: values must come from a pool, any pick is a valid id
    std::mt19937 rng(4);
    for (const auto& block : m.shops) {
        for (const auto& [id, cat] : block) {
            std::uint32_t rolled = m.roll_item(cat, rng);
            check(rolled != 0, "roll_item returned 0 for a category with items");
            (void)id;
        }
    }
    std::printf("%s: %zu blocks, %zu pools parsed\n",
                g_failures == 0 ? "PASS" : "FAIL", m.shop_count(), m.pools.size());
    return g_failures == 0 ? 0 : 1;
}
